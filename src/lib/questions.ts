export function parseGradeClass(grade: string | number, classNo: string | number) {
  const g = Number(grade);
  const c = Number(classNo);
  if (!Number.isInteger(g) || g < 1 || g > 3) return null;
  if (!Number.isInteger(c) || c < 1 || c > CLASS_COUNT) return null;
  return { grade: g as 1 | 2 | 3, classNo: c };
}
